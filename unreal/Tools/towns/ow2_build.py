# The second Overworld (Overworld2): a copy of the Overworld level with its landscape, mountain / tree props and foliage
# houses stripped and a terraced voxel terrain (ow_voxel.py -> Saved/PlayTest/ow_voxel.json) spawned by PCG_Overworld2
# instead; portals, player starts, landmarks, enemies and the hand-placed settlement houses are set down on the new ground.
OW="/Game/Wot/Maps/Overworld/Overworld"; OW2_DIR="/Game/Wot/Maps/Overworld2"; OW2=OW2_DIR+"/Overworld2"
PROJ_SAVED="/Users/bob/well-known-game-studio/wot_a_good_game/unreal/Saved/PlayTest/"
HOUSE=M+"small/small_prop_house.small_prop_house"; BIG=M+"small/small_prop_big_building.small_prop_big_building"
def _read(name):
    """A JSON file staged under Saved/PlayTest (read_file takes absolute paths and at most 80 KB a call: ow_voxel.py
    splits its output into numbered parts)."""
    if name=="ow_voxel.json":
        n=int(str(T(AS+"read_file",{"file_path":PROJ_SAVED+"ow_voxel_parts/count.txt"})).strip())   # T parses JSON-looking replies
        return json.loads("".join(str(T(AS+"read_file",{"file_path":PROJ_SAVED+"ow_voxel_parts/%04d.txt"%i})) for i in range(n)))
    v=T(AS+"read_file",{"file_path":PROJ_SAVED+name})
    return v if isinstance(v,(list,dict)) else json.loads(str(v))
def run():
    out={}
    data=_read("ow_voxel.json"); sites=_read("ow_sites.json"); houses=_read("ow_houses.json")
    x0,y0,cell,step=data["x0"],data["y0"],data["cell"],data["step"]; H=data["heights"]; ny=len(H); nx=len(H[0])
    def hz(x,y):
        i=int((x-x0)//cell); j=int((y-y0)//cell)
        if 0<=i<nx and 0<=j<ny: return max(0,H[j][i])*step
        return 0.0
    cur=T(SC+"get_current_level",{})
    if cur and cur!=OW2: save([cur])   # load_level refuses to leave a dirty level
    if not T(AS+"exists",{"path":OW2}): out["dup"]=T(AS+"duplicate",{"path":OW,"new_path":OW2})
    if T(SC+"get_current_level",{})!=OW2: T(SC+"load_level",{"level_path":OW2})
    # strip the old terrain and anything a previous run of this script placed
    n=0; keep=[]
    for p in find_by_tag("OwHouse"): remove(p); n+=1   # houses and the fence a previous run placed, before listing what stays
    for a in (T(SC+"find_actors",{"name":"","tag":"","collision_channels":[]}) or []):
        p=a["refPath"]; cls=p.split(".")[-1]
        if cls.startswith(("Landscape","BP_LandscapeLayers","PCGWorldActor","InstancedFoliageActor","BP_LevelBounds","PCG_Overworld2","PCGVolume")): remove(p); n+=1
        else: keep.append(p)
    out["removed"]=n
    # ---- the terrain graph: one spawner per material, run-merged slabs as world-space points scaled to their boxes
    g=create_graph("PCG_Overworld2",OW2_DIR); B=G(g); y=0
    groups={}; order=[]
    for bx in data["boxes"]:
        m=bx[0]
        if m not in groups: groups[m]=[]; order.append(m)
        groups[m].append(bx)
    for gi,m in enumerate(order):
        pts=[point(x,yy,z,0,(sx/100.0,sy/100.0,sz/100.0),50) for (_,x,yy,z,sx,sy,sz) in groups[m]]
        names=[]
        for ci in range(0,len(pts),1200):
            nm=f"T{gi}_{ci//1200}"; B.node("Create Points",nm,{"pointsToCreate":pts[ci:ci+1200],"coordinateSpace":"World"},title=f"{m} {ci//1200}",x=0,y=y); names.append(nm); y+=1
        B.node("Merge Points",f"T{gi}M",{},title=m,x=1,y=y-1)
        for nm in names: B.link(nm,"Out",f"T{gi}M","In")
        mat=WATER if m=="MI_VoxelWater" else MAT(m)
        B.node("Static Mesh Spawner",f"T{gi}S",{},title=f"terrain {m}",x=2,y=y-1); B.set_meshes(f"T{gi}S",[(CUBE,1,[mat])]); B.link(f"T{gi}M","Out",f"T{gi}S","In")
        y+=1
    out["terrain_boxes"]=len(data["boxes"])
    # ---- trees: the kit's voxel trees, no collision (the map table must stay walkable), yaw from position
    kinds={}; korder=[]
    for (x,yy,z,kind,sc) in data["trees"]:
        if kind not in kinds: kinds[kind]=[]; korder.append(kind)
        kinds[kind].append(point(x,yy,z,float((int(x)*7+int(yy)*13)%360),sc,50))
    for ki,kind in enumerate(korder):
        pts=kinds[kind]; names=[]
        for ci in range(0,len(pts),1200):
            nm=f"F{ki}_{ci//1200}"; B.node("Create Points",nm,{"pointsToCreate":pts[ci:ci+1200],"coordinateSpace":"World"},title=f"{kind} {ci//1200}",x=0,y=y); names.append(nm); y+=1
        B.node("Merge Points",f"F{ki}M",{},title=kind,x=1,y=y-1)
        for nm in names: B.link(nm,"Out",f"F{ki}M","In")
        B.node("Static Mesh Spawner",f"F{ki}S",{},title=f"trees {kind}",x=2,y=y-1); B.link(f"F{ki}M","Out",f"F{ki}S","In")
        sel=B.selector_path(f"F{ki}S")
        T(OB+"set_properties",{"instance":ref(sel),"values":json.dumps({"MeshEntries":[{"weight":1,"descriptor":{"staticMesh":ref(kit_mesh(kind)),"bodyInstance":{"collisionProfileName":"NoCollision","collisionEnabled":"NoCollision"}}}]})})
        y+=1
    out["trees"]=len(data["trees"])
    T(PC+"SetGraphDescription",{"graph":ref(g),"description":"Overworld2 terrain: generated by unreal/Tools/towns/ow_voxel.py + ow2_build.py (run_town.py --overworld2) from blender/overworld-full.png. Do not edit by hand."})
    vol,msgs=spawn_and_run(g,"PCG_Overworld2",32000); out["vol"]=vol; out["msgs"]=str(msgs)[:300]
    # ---- set everything down on the new ground
    moved=0
    for p in keep:
        cls=p.split(".")[-1]
        if not cls.startswith(("Portal_C","PlayerStart","StaticMeshActor","Minion")): continue
        try:
            xf=T(AC+"get_actor_transform",{"actor":ref(p)}); loc=xf["location"]; rot=xf["rotation"]
            z=hz(loc["x"],loc["y"])+(100 if cls.startswith(("Portal_C","PlayerStart")) else 0)
            move_actor(p,(loc["x"],loc["y"],z),rot["yaw"]); moved+=1
        except Exception as e: out["move_err_"+cls]=str(e)[:80]
    out["moved"]=moved
    for i,h in enumerate(houses):
        x,yy=h["x"],h["y"]; mesh=BIG if "big" in h["mesh"] else HOUSE
        place_mesh(mesh,f"OwHouse{i}",(x,yy,hz(x,yy)),float((int(x)*7+int(yy)*13)%360),1.0,None,tag="OwHouse")
    out["houses"]=len(houses)
    # ---- the fence round the whole table
    cx=x0+nx*cell/2; cy=y0+ny*cell/2
    bp=place_class(LEVEL_BOUNDS_BP,"LevelBounds",(cx,cy,1500),0,1.0,tag="OwHouse")
    if bp: T(OB+"set_properties",{"instance":ref(bp+".Bounds"),"values":json.dumps({"BoxExtent":f"(X={nx*cell/2-50},Y={ny*cell/2-50},Z=6000)"})})
    save([OW2,g.split(".")[0]]); out["saved"]=True
    return out
