def circle(cx,cy,r,n=16,start=0.0):
    return [(cx+r*math.cos(start+2*math.pi*i/n), cy+r*math.sin(start+2*math.pi*i/n)) for i in range(n)]
def rect(x0,y0,x1,y1):
    return [(x0,y0),(x1,y0),(x1,y1),(x0,y1)]

