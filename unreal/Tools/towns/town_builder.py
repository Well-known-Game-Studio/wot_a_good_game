def build_town_graph(spec):
    """Creates the per-town PCG graph from a relief spec: data nodes (Create Points) per town, all processing in the shared
    subgraphs under /Game/Wot/Towns/Common/PCG (pcg_subgraphs.py). Sections are boxed and commented. Returns (graphPath, info)."""
    g=create_graph(spec["graph_name"], spec["folder"]); B=G(g); info={"graph":g}
    T(PC+"SetGraphDescription",{"graph":ref(g),"description":f"{spec.get('town','')}: generated by unreal/Tools/towns (run_town.py {spec.get('town','')}) from specs_*.py + relief.py. Only Create Points data and Static Mesh Spawners live here; the point logic is in the shared PCGS_* subgraphs. Do not edit by hand: change the spec or a subgraph and rebuild."})
    R=gv(spec,"_relief"); y=0
    def box(names,text,color): comment_box(B,names,text,color)
    # ---------------- exclusions and plazas ----------------
    excl=[]; sect=[]
    if gv(spec,"exclusions"):
        pts=[]
        for (ex,ey,hx,hy) in spec["exclusions"]:
            p=point(ex,ey,0,0,1.0,50); p["boundsMin"]={"x":-hx,"y":-hy,"z":-2500}; p["boundsMax"]={"x":hx,"y":hy,"z":3500}; pts.append(p)
        B.node("Create Points","ExclPts",{"pointsToCreate":pts,"coordinateSpace":"World"},title="Hand-placed exclusions",x=0,y=y,comment="boxes around landmarks, stairs and Waygates: nothing is placed inside"); excl.append(("ExclPts","Out")); sect.append("ExclPts"); y+=1
    plaza_surfs=[]
    for i,pz in enumerate(gv(spec,"plazas") or []):
        pts=[point(pt[0],pt[1],(pt[2] if len(pt)>2 else gv(pz,"z",0)),0,1.0,50) for pt in pz["pts"]]
        B.node("Create Points",f"PlazaPts{i}",{"pointsToCreate":pts,"coordinateSpace":"World"},title=f"Plaza {i} outline",x=0,y=y)
        B.sub(SUBS["Plaza"],f"Plaza{i}",{"bLinear":gv(pz,"linear",False)},title=f"Plaza {i}",x=1,y=y)
        B.link(f"PlazaPts{i}","Out",f"Plaza{i}","Outline"); plaza_surfs.append((f"Plaza{i}","Surface")); sect+=[f"PlazaPts{i}",f"Plaza{i}"]
        if R is None or gv(pz,"tiles",False):
            B.node("Static Mesh Spawner",f"PlazaSpawn{i}",{},title=f"Plaza {i} tiles",x=2,y=y); B.set_meshes(f"PlazaSpawn{i}",[(CUBE,1,[pz["mat"]])]); B.link(f"Plaza{i}","Tiles",f"PlazaSpawn{i}","In"); sect.append(f"PlazaSpawn{i}")
        y+=1
    box(sect,"EXCLUSIONS AND PLAZAS\nHand-placed exclusion boxes and plaza outlines -> PCGS_Plaza (Surface is an exclusion for houses and foliage; tiles only when the plaza asks for them: the relief terrain paints plaza pavement). Plaza furniture is placed by relief.plaza_furniture (see the furniture section).",(0.55,0.45,0.2)); y+=1
    # ---------------- roads, water, walls ----------------
    sect=[]; rows={}; groups={}; gorder=[]; wall_nodes=[]
    for i,rd in enumerate(spec["roads"]):
        w=gv(rd,"width",7); ts=tuple(gv(rd,"tile_scale",(1,1,0.06))); tz=gv(rd,"tile_z",0); step=gv(rd,"tile_step",100); pitch=gv(rd,"row_pitch",100)
        key=(w,ts,tz,pitch)
        if key not in rows:
            name=f"Row{len(rows)}"
            B.node("Create Points",name,{"pointsToCreate":[point(0,(k-(w-1)/2.0)*pitch,tz,0,ts,50) for k in range(w)],"coordinateSpace":"World"},title=f"Tile row w={w}",x=0,y=y,comment="one tile per lane; copied onto every road sample"); rows[key]=name; sect.append(name); y+=1
        pts=[point(pt[0],pt[1],(pt[2] if len(pt)>2 else 0),0,1.0,50) for pt in rd["pts"]]
        closed=gv(rd,"closed",False); kind=gv(rd,"kind","road")
        B.node("Create Points",f"RoadPts{i}",{"pointsToCreate":pts,"coordinateSpace":"World"},title=f"{kind} {i}: {gv(rd,'name','')}",x=0,y=y)
        params={"bClosedLoop":closed,"bLinear":gv(rd,"linear",False),"DistanceIncrement":float(step),"KeepRatio":float(rd["keep"]) if gv(rd,"keep") is not None else 1.0}
        B.sub(SUBS["Road"],f"Road{i}",params,title=f"{kind} {i}",x=1,y=y)
        B.link(f"RoadPts{i}","Out",f"Road{i}","Path"); B.link(rows[key],"Out",f"Road{i}","Row"); sect+=[f"RoadPts{i}",f"Road{i}"]
        mat=gv(rd,"mat",spec["road_mat"]); mesh=gv(rd,"mesh",CUBE)
        # the relief paints carved roads (and water channels with a water plane) into the terrain: their tile slabs would only
        # z-fight / float at the steps, so such groups keep their points for exclusions but spawn no tiles
        painted=bool(R) and not gv(rd,"nocarve",False) and kind in ("road","water")
        gk=(mat,mesh,kind,painted)
        if gk not in groups: groups[gk]=[]; gorder.append(gk)
        groups[gk].append(f"Road{i}"); y+=1
    road_merges=[]; other_merges=[]; gsrc={}
    for j,gk in enumerate(gorder):
        mat,mesh,kind,painted=gk
        B.node("Merge Points",f"GrpMerge{j}",{},title=f"{kind} tiles"+(" (painted: exclusion only)" if painted else ""),x=2,y=y)
        for n in groups[gk]: B.link(n,"Tiles",f"GrpMerge{j}","In")
        gsrc[gk]=f"GrpMerge{j}"; sect.append(f"GrpMerge{j}")
        if kind=="wall": wall_nodes.append(f"GrpMerge{j}")
        elif kind=="road": road_merges.append(f"GrpMerge{j}")
        else: other_merges.append(f"GrpMerge{j}")
        y+=1
    B.node("Merge Points","RoadAll",{},title="all road tiles",x=3,y=y)
    for n in road_merges: B.link(n,"Out","RoadAll","In")
    B.node("Bounds Modifier","RoadExcl",{"mode":"Set","boundsMin":{"x":-30,"y":-30,"z":-3000},"boundsMax":{"x":30,"y":30,"z":3000}},title="Road exclusion",x=4,y=y,comment="tall thin boxes: houses and foliage keep off the pavement at any terrace height"); sect+=["RoadAll","RoadExcl"]
    B.link("RoadAll","Out","RoadExcl","In"); y+=1
    for j,gk in enumerate(gorder):
        mat,mesh,kind,painted=gk; src=gsrc[gk]
        if kind=="nobuild" or painted: continue
        if kind=="wall":
            B.node("Difference",f"WallCut{j}",{"densityFunction":"Binary","mode":"Inferred"},title="Gates where roads cross",x=3,y=y,comment="roads, stairs and hand exclusions open the wall")
            B.link(src,"Out",f"WallCut{j}","Source"); B.link("RoadExcl","Out",f"WallCut{j}","Differences")
            for (n_,p_) in excl: B.link(n_,p_,f"WallCut{j}","Differences")
            src=f"WallCut{j}"; sect.append(f"WallCut{j}")
        B.node("Static Mesh Spawner",f"GrpSpawn{j}",{},title=f"{kind} spawner",x=4,y=y); B.set_meshes(f"GrpSpawn{j}",[(mesh,1,[mat] if mat else None)])
        B.link(src,"Out",f"GrpSpawn{j}","In"); sect.append(f"GrpSpawn{j}"); y+=1
    box(sect,"ROADS, WATER, WALLS\nEach road: its path points + a tile row -> PCGS_Road (spline, samples, tiles, gaps). Groups by material/kind are merged; painted roads (the relief carved them into the terrain) only feed the exclusions; piers, bridges and walls spawn their tiles, walls cut where roads cross.",(0.35,0.35,0.35)); y+=1
    # ---------------- hand-placed point sets (relief): house slots, street lines, towers, plaza furniture ----------------
    def chunked_points(prefix,pts,x,y,title="",chunk=1200):
        """Create Points nodes in chunks merged into one; returns (merge node name, node rows used)."""
        names=[]
        for ci in range(0,max(1,len(pts)),chunk):
            nm=f"{prefix}{ci//chunk}"; B.node("Create Points",nm,{"pointsToCreate":pts[ci:ci+chunk],"coordinateSpace":"World"},title=f"{title} {ci//chunk}",x=x,y=y+ci//chunk); names.append(nm)
        B.node("Merge Points",f"{prefix}Merge",{},title=title,x=x+1,y=y)
        for nm in names: B.link(nm,"Out",f"{prefix}Merge","In")
        return f"{prefix}Merge", max(1,len(names)), names+[f"{prefix}Merge"]
    sect=[]
    for li,ls in enumerate(gv(spec,"line_sets") or []):
        if not ls["pts"]: continue
        sc=ls["scale"]; nm,cnt,used=chunked_points(f"Line{li}",[point(x,yy,z,yaw,(sc[0],sc[1],sc[2]),50) for (x,yy,z,yaw) in ls["pts"]],0,y,title=f"line {li} {ls['name']}")
        B.node("Static Mesh Spawner",f"LineSpawn{li}",{},title=f"line {li} {ls['name']}",x=2,y=y); B.set_meshes(f"LineSpawn{li}",[(ls["mesh"],1,ls["mats"])]); B.link(nm,"Out",f"LineSpawn{li}","In"); sect+=used+[f"LineSpawn{li}"]; y+=cnt
    for fi,fs in enumerate(gv(spec,"furniture_sets") or []):
        if not fs["pts"]: continue
        sc=fs["scale"]; nm,cnt,used=chunked_points(f"Furn{fi}",[point(x,yy,z,yaw,(sc[0],sc[1],sc[2]),50) for (x,yy,z,yaw) in fs["pts"]],0,y,title=f"furniture {fi} {fs['name']}")
        B.node("Static Mesh Spawner",f"FurnSpawn{fi}",{},title=f"furniture {fi} {fs['name']}",x=2,y=y); B.set_meshes(f"FurnSpawn{fi}",[(fs["mesh"],1,fs["mats"])]); B.link(nm,"Out",f"FurnSpawn{fi}","In"); sect+=used+[f"FurnSpawn{fi}"]; y+=cnt
    for ti,ts_ in enumerate(gv(spec,"tower_sets") or []):
        if not ts_["pts"]: continue
        sc=ts_["scale"]; nm,cnt,used=chunked_points(f"Tower{ti}",[point(x,yy,z,yaw,(sc[0],sc[1],sc[2]),50) for (x,yy,z,yaw) in ts_["pts"]],0,y,title=f"towers {ts_['name']}")
        B.node("Static Mesh Spawner",f"TowerSpawn{ti}",{},title=f"towers {ts_['name']}",x=2,y=y); B.set_meshes(f"TowerSpawn{ti}",[(ts_["mesh"],1,ts_["mats"])]); B.link(nm,"Out",f"TowerSpawn{ti}","In"); sect+=used+[f"TowerSpawn{ti}"]; y+=cnt
    box(sect,"STREET LINES, PLAZA FURNITURE, WALL TOWERS\nPoints placed by relief.py's placement rules (occupancy registry: nothing on pavement, in doorways, on stairs or on another footprint) and spawned as-is.",(0.2,0.5,0.45)); y+=1
    # ---------------- houses ----------------
    hs=gv(spec,"houses"); sets=gv(spec,"house_sets") or {}; hsl=gv(spec,"house_slots") or {}
    house_nodes=[]; sect=[]
    def house_pipeline(tag,cfg):
        nonlocal y
        pts=hsl.get(tag) if tag in hsl else None
        if not pts or not cfg: return
        nm,cnt,used=chunked_points(f"Slots{tag}",[point(x,yy,z,yaw,1.0,50) for (x,yy,z,yaw) in pts],0,y,title=f"house slots {tag or 'default'}")
        smin,smax=cfg["scale"]; fp=gv(cfg,"footprint",(-740,-420,560,560)); jit=gv(cfg,"jitter",120); sh=gv(cfg,"excl_shrink",0.55)
        params={"OffsetMin":{"x":-jit,"y":-40,"z":0},"OffsetMax":{"x":jit,"y":40,"z":0},"ScaleMin":{"x":smin,"y":smin,"z":smin},"ScaleMax":{"x":smax,"y":smax,"z":smax},"Ratio":float(gv(cfg,"keep",0.9)),
                "CoreMin":{"x":fp[0]*sh,"y":fp[1]*sh,"z":0},"CoreMax":{"x":fp[2]*sh,"y":fp[3]*sh,"z":700},"FootMin":{"x":fp[0],"y":fp[1],"z":0},"FootMax":{"x":fp[2],"y":fp[3],"z":700}}
        B.sub(SUBS["Houses"],f"Houses{tag}",params,title=f"Houses {tag or 'default'}",x=2,y=y)
        B.link(nm,"Out",f"Houses{tag}","Slots")
        B.link("RoadExcl","Out",f"Houses{tag}","Exclusions")
        for n in wall_nodes+other_merges: B.link(n,"Out",f"Houses{tag}","Exclusions")
        for (n,p) in plaza_surfs+excl: B.link(n,p,f"Houses{tag}","Exclusions")
        for n in house_nodes: B.link(n,"Houses",f"Houses{tag}","Exclusions")   # later sets avoid earlier houses
        B.node("Static Mesh Spawner",f"HouseSpawn{tag}",{"bApplyMeshBoundsToPoints":True},title=f"Houses {tag or 'default'}",x=3,y=y); B.set_meshes(f"HouseSpawn{tag}",cfg["entries"])
        B.link(f"Houses{tag}","Houses",f"HouseSpawn{tag}","In"); house_nodes.append(f"Houses{tag}"); sect.extend(used+[f"Houses{tag}",f"HouseSpawn{tag}"]); y+=cnt
    house_pipeline("",hs)
    for k in sets: house_pipeline(k,sets[k])
    box(sect,"HOUSES\nSlots from relief.road_props (per street set) -> PCGS_Houses (jitter, scale, keep ratio, core clear of roads/plazas/walls/earlier sets, footprint, no overlaps) -> spawner with the set's mesh/material entries.",(0.5,0.3,0.3)); y+=1
    # ---------------- terrain ----------------
    terr=gv(spec,"terrain"); sect=[]
    if terr:
        tg={}
        for (m,tx,ty,tz,sx,sy,sz) in terr["boxes"]:
            tg.setdefault(m,[]).append(point(tx,ty,tz,0,(sx/100.0,sy/100.0,sz/100.0),50))
        for gi,(m,pts) in enumerate(tg.items()):
            mat=terr["palette"][m] if m in terr["palette"] else m
            mg,cnt,used=chunked_points(f"Terr{gi}",pts,0,y,title=f"terrain {m.split('/')[-1]}")
            B.node("Static Mesh Spawner",f"TerrSpawn{gi}",{},title=f"terrain {m.split('/')[-1]}",x=2,y=y); B.set_meshes(f"TerrSpawn{gi}",[(CUBE,1,[mat])])
            B.link(mg,"Out",f"TerrSpawn{gi}","In"); sect+=used+[f"TerrSpawn{gi}"]; y+=cnt
    box(sect,"TERRAIN\nRun-merged voxel boxes from the relief heightfield (one spawner per palette material: grass, rock, sand, snow, pavement, water bed).",(0.3,0.45,0.25)); y+=1
    # ---------------- ground lattice and foliage ----------------
    fo=spec["foliage"]; E=fo["extent"]; cx,cy=spec["center"]; sect=[]
    lat=gv(spec,"lattice") or []
    mg,cnt,used=chunked_points("Lat",[point(px,py,pz,0,1.0,50) for (px,py,pz) in lat],0,y,title="ground lattice"); sect+=used
    B.node("Create Points","Center",{"pointsToCreate":[point(cx,cy,0,0,1.0,10)],"coordinateSpace":"World"},title="Town centre",x=0,y=y+cnt); sect.append("Center")
    B.sub(SUBS["Lattice"],"Ground",{"OffsetMin":{"x":-110,"y":-110,"z":0},"OffsetMax":{"x":110,"y":110,"z":0},"MaximumDistance":float(fo["forest_radius"])},title="Ground (density = distance)",x=2,y=y)
    B.link(mg,"Out","Ground","Lattice"); B.link("Center","Out","Ground","Center")
    B.link("RoadExcl","Out","Ground","Exclusions")
    for n in wall_nodes+other_merges: B.link(n,"Out","Ground","Exclusions")
    for n in house_nodes: B.link(n,"Houses","Ground","Exclusions")
    for (n,p) in plaza_surfs+excl: B.link(n,p,"Ground","Exclusions")
    sect.append("Ground"); y+=max(cnt,1)+1
    clip=gv(fo,"clip_density",1.0); dens=gv(spec,"lattice_density",1.0)
    def scatter(name,lo,hi,ratio,entries,smin,smax,prune=None,yawrand=True):
        nonlocal y
        if ratio<=0 or not entries: return
        ratio=min(1.0,ratio*dens); hi=min(hi,clip); pr=prune or 50
        B.sub(SUBS["Scatter"],f"{name}",{"LowerBound":float(lo),"UpperBound":float(hi),"Ratio":float(ratio),"RotationMax":{"pitch":0,"yaw":360 if yawrand else 0,"roll":0},
              "ScaleMin":{"x":smin,"y":smin,"z":smin},"ScaleMax":{"x":smax,"y":smax,"z":smax},"BoundsMin":{"x":-pr,"y":-pr,"z":0},"BoundsMax":{"x":pr,"y":pr,"z":pr}},title=f"{name}: density {lo}-{hi}",x=3,y=y)
        B.link("Ground","Ground",name,"Ground")
        B.node("Static Mesh Spawner",f"{name}Spawn",{},title=name,x=4,y=y); B.set_meshes(f"{name}Spawn",entries); B.link(name,"Points",f"{name}Spawn","In")
        sect.extend([name,f"{name}Spawn"]); y+=1
    trees=fo["trees"]; ts=gv(fo,"tree_scale",(0.9,1.4))
    scatter("ForestTrees",fo["forest_band"][0],fo["forest_band"][1],fo["forest_ratio"],trees,ts[0],ts[1],prune=160)
    scatter("EdgeTrees",fo["edge_band"][0],fo["edge_band"][1],fo["edge_ratio"],trees,ts[0]*0.9,ts[1]*0.9,prune=200)
    scatter("TownTrees",fo["town_band"][0],fo["town_band"][1],fo["town_ratio"],gv(fo,"town_trees",trees),ts[0]*0.9,ts[1]*0.85,prune=300)
    scatter("Bushes",0.0,1.0,fo["bush_ratio"],[(MESH["bush1"],1,None),(MESH["bush2"],1,None)],0.7,1.2)
    scatter("Grass",0.0,1.0,fo["grass_ratio"],[(MESH["grass"],1,None)],0.9,1.6)
    scatter("Mushrooms",fo["forest_band"][0],1.0,gv(fo,"mush_ratio",0),[(MESH["mush1"],1,None),(MESH["mush2"],1,None),(MESH["mush3"],1,None)],0.8,1.3)
    for ex in gv(fo,"extra") or []:
        scatter(ex["name"],ex["band"][0],ex["band"][1],ex["ratio"],ex["entries"],ex["scale"][0],ex["scale"][1],prune=gv(ex,"prune"))
    box(sect,"GROUND LATTICE AND FOLIAGE\nThe relief's lattice (every unpaved cell, already clear of slots, stairs, lines and furniture) -> PCGS_Lattice (jitter, density = distance from the centre, minus exclusions) -> one PCGS_Scatter per band (forest / edge / town trees, bushes, grass, mushrooms, extras) -> spawners.",(0.2,0.4,0.2))
    # the comment box ids ride along in the description so the next in-place rebuild can remove them
    T(PC+"SetGraphDescription",{"graph":ref(g),"description":f"{spec.get('town','')}: generated by unreal/Tools/towns (run_town.py {spec.get('town','')}) from specs_*.py + relief.py. Only Create Points data and Static Mesh Spawners live here; the point logic is in the shared PCGS_* subgraphs. Do not edit by hand: change the spec or a subgraph and rebuild. [boxes:{','.join(getattr(B,'boxes',[]))}]"})
    save([g.split(".")[0]])
    info["nodes"]=len(B.nodes)
    return g,info

def _rot(yaw):
    if isinstance(yaw,(list,tuple)): return {"pitch":yaw[0],"yaw":yaw[1],"roll":yaw[2]}
    return {"pitch":0,"yaw":yaw,"roll":0}
def place_mesh(path,label,loc,yaw=0,scale=1.0,mats=None,tag=TOWNPROP,tags=(),props=None):
    s=scale if isinstance(scale,(list,tuple)) else (scale,scale,scale)
    a=T(SC+"add_to_scene_from_asset",{"asset_path":path,"name":label,"xform":{"location":{"x":loc[0],"y":loc[1],"z":loc[2] if len(loc)>2 else 0},"rotation":_rot(yaw),"scale":{"x":s[0],"y":s[1],"z":s[2]}}})
    ap=a["refPath"] if isinstance(a,dict) else a
    if mats:
        comps=T(AC+"get_components",{"actor":ref(ap),"component_type":ref("/Script/Engine.StaticMeshComponent")})
        for c in comps:
            T(OB+"set_properties",{"instance":ref(c["refPath"]),"values":json.dumps({"OverrideMaterials":[ref(m) if m else "None" for m in mats]})})
    if tag: T(AC+"add_tag",{"actor":ref(ap),"tag":tag})
    for t_ in tags: T(AC+"add_tag",{"actor":ref(ap),"tag":t_})
    if props:
        props=dict(props); extra_tags=props.pop("Tags",None) or []
        if props: T(OB+"set_properties",{"instance":ref(ap),"values":json.dumps(props)})
        for t_ in extra_tags: T(AC+"add_tag",{"actor":ref(ap),"tag":t_})  # Tags is an array: set_properties cannot grow it
    return ap
def place_class(cls,label,loc,yaw=0,scale=1.0,tag=TOWNPROP):
    s=scale if isinstance(scale,(list,tuple)) else (scale,scale,scale)
    a=T(SC+"add_to_scene_from_class",{"actor_type":ref(cls),"name":label,"xform":{"location":{"x":loc[0],"y":loc[1],"z":loc[2] if len(loc)>2 else 0},"rotation":_rot(yaw),"scale":{"x":s[0],"y":s[1],"z":s[2]}}})
    ap=a["refPath"] if isinstance(a,dict) else a
    if tag: T(AC+"add_tag",{"actor":ref(ap),"tag":tag})
    return ap
def move_actor(path,loc,yaw=None):
    xf={"location":{"x":loc[0],"y":loc[1],"z":loc[2]}}
    if yaw is not None: xf["rotation"]={"pitch":0,"yaw":yaw,"roll":0}
    return T(AC+"set_actor_transform",{"actor":ref(path),"xform":xf,"worldspace":True})
def find_by_label(label):
    return [a["refPath"] for a in (T(SC+"find_actors",{"name":label,"tag":"","collision_channels":[]}) or [])]
def find_by_tag(tag):
    return [a["refPath"] for a in (T(SC+"find_actors",{"name":"","tag":tag,"collision_channels":[]}) or [])]
def remove(path): return T(SC+"remove_from_scene",{"actor":ref(path)})
def clean_town(extra_labels=()):
    n=0
    for a in (T(SC+"find_actors",{"name":"","tag":"","collision_channels":[]}) or []):
        p=a["refPath"]; cls=p.split(".")[-1]
        if cls.startswith("PCG_") or cls.startswith("PCGVolume"): remove(p); n+=1
    for p in find_by_tag(TOWNPROP): remove(p); n+=1
    for lab in extra_labels:
        for p in find_by_label(lab): remove(p); n+=1
    return n
def ground_z(x,y):
    """Height of the topmost TownGround-ish collision at (x,y) via a world trace (falls back to 0)."""
    try:
        d=T(SC+"trace_world",{"start":{"x":x,"y":y,"z":4000},"end":{"x":x,"y":y,"z":-4000}})
        return 4000-float(d) if d is not None else 0
    except Exception: return 0
def spawn_and_run(graph,label,extent):
    inst=T(PC+"SpawnGraphInstance",{"graph":ref(graph),"name":label,"transform":{"location":{"x":0,"y":0,"z":0},"rotation":{"pitch":0,"yaw":0,"roll":0},"scale":{"x":extent/100.0,"y":extent/100.0,"z":10}},"jsonParams":""})
    vol=gv(gv(inst,"actor") or {},"refPath")
    msgs=T(PC+"ExecuteGraphInstance",{"pCGVolume":ref(vol)}) if vol else "no volume"
    return vol,msgs
def build_level(spec,extra_clean=()):
    out={"cleaned":clean_town(extra_clean)}
    g,info=build_town_graph(spec); out["info"]=info
    placed=0; R=gv(spec,"_relief")
    def lift(loc,absolute=False):
        if R is None or absolute: return loc
        return (loc[0],loc[1],R.zat(loc[0],loc[1])+(loc[2] if len(loc)>2 else 0))
    for item in gv(spec,"props") or []:
        absolute=len(item)>7 and item[7]=="abs"
        if item[0]=="mesh":
            path,label,loc,yaw,scale,mats=item[1:7]; place_mesh(path,label,lift(loc,absolute),yaw,scale,mats); placed+=1
        elif item[0]=="ground":
            if R is not None: continue  # the relief terrain is the ground; a flat plane underneath only confuses the navmesh
            path,label,loc,yaw,scale,mats=item[1:7]; place_mesh(path,label,loc,yaw,scale,mats,tags=(GROUND_TAG,)); placed+=1
        elif item[0]=="class":
            cls,label,loc,yaw,scale=item[1:6]; ap=place_class(cls,label,lift(loc,absolute),yaw,scale); placed+=1
            if len(item)>6 and item[6]: T(OB+"set_properties",{"instance":ref(ap),"values":json.dumps(item[6])})
        elif item[0]=="actor":
            path,label,loc,yaw,scale,props=item[1:7]; place_mesh(path,label,lift(loc,absolute),yaw,scale,None,props=props); placed+=1
        elif item[0]=="npc":
            label,loc,yaw,props=item[1:5]; cls=item[5] if len(item)>5 and item[5] else "/Game/Wot/NPCs/NPC_Villager_BP"
            z=(R.zat(loc[0],loc[1]) if R is not None else ground_z(loc[0],loc[1]))+96
            place_mesh(cls,label,(loc[0],loc[1],z),yaw,1.0,None,props=props); placed+=1
    out["placed"]=placed
    vol,msgs=spawn_and_run(g,spec["graph_name"],spec["foliage"]["extent"]*2); out["vol"]=vol; out["msgs"]=msgs
    dl=gv(spec,"dialogue")
    if dl:
        DT="editor_toolset.toolsets.data_table.DataTableTools."; table=ref("/Game/Wot/DataTables/DT_HybridRPG_Dialogue.DT_HybridRPG_Dialogue")
        existing=set(T(DT+"list_rows",{"data_table":table}))
        new=[k for k in dl if k not in existing]
        if new: T(DT+"add_rows",{"data_table":table,"row_names":new})
        T(DT+"set_rows",{"data_table":table,"values":json.dumps({k:{"dialogueText":v[0],"nextRow":v[1]} for k,v in dl.items()})})
        existing|=set(dl.keys())
        missing=[it[1] for it in (gv(spec,"props") or []) if it[0]=="npc" and it[4].get("CurrentRowName") and it[4]["CurrentRowName"] not in existing]
        if missing: out["dialogue_missing"]=missing   # an NPC whose first row is not in the table would lock the player with nothing to say
        save(["/Game/Wot/DataTables/DT_HybridRPG_Dialogue"]); out["dialogue_rows"]=len(dl)
    for (label,loc,yaw) in gv(spec,"moves") or []:
        for p in find_by_label(label): move_actor(p,loc,yaw)
    town=gv(spec,"town")
    if town:
        for p in find_by_label("OverworldPortal"):
            T(OB+"set_properties",{"instance":ref(p),"values":json.dumps({"ToLevel":"Overworld","PortalName":f"{town}Overworld","Enabled":True})})
        for p in find_by_label("OverworldPlayerStart"):
            T(OB+"set_properties",{"instance":ref(p),"values":json.dumps({"PlayerStartTag":f"Overworld{town}"})})
        out["portal_wired"]=True
    ls=gv(spec,"level_scale")
    if ls:
        for lab in ("NavMeshBounds","BP_LevelBounds"):
            for p in find_by_label(lab):
                T(AC+"set_actor_transform",{"actor":ref(p),"xform":{"location":{"x":0,"y":0,"z":500 if lab=="NavMeshBounds" else 0},"scale":{"x":ls[0],"y":ls[1],"z":ls[2]*3}},"worldspace":True})
    return out
